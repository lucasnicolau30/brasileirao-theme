// Ordem dos times: agrupados por estado (o estado vem de `uf`), os estados na ordem em que aparecem neste arquivo (Rio, São
// Paulo, Minas, Rio Grande do Sul, Bahia, Ceará, Paraná, Pernambuco, Pará, Amazonas, Goiás). Dentro de cada estado, por títulos, comparando nesta ordem:
// Mundial, Libertadores, Brasileirão, Copa do Brasil, Sul-Americana, Copa do Nordeste, Séries B, C e D e Copa Verde (mais títulos primeiro) e, por último, o Estadual: sem troféu nacional que desempate, vale o estadual
// (o estadual só desempata quando não há troféu nacional que desempate). Se os dois têm exatamente a mesma quantidade de títulos em todas essas competições, vem primeiro
// quem conquistou antes o título mais importante (ano mais antigo da primeira competição da lista; empatando o ano, vale a competição seguinte). Persistindo o empate, vale a ordem do arquivo.
const estado = (t) => t.uf;
const estados = [...new Set(times.map(estado))];
const CRITERIOS = [
  "mundial",
  "libertadores",
  "brasileirao",
  "copaDoBrasil",
  "sulAmericana",
  "copaDoNordeste",
  "serieB",
  "serieC",
  "serieD",
  "copaVerde",
  "estadual",
];
const primeiroAno = (t, k) =>
  t.titles[k].length ? Math.min(...t.titles[k]) : Infinity;
const porTitulos = (a, b) => {
  for (const k of CRITERIOS) {
    const d = b.titles[k].length - a.titles[k].length;
    if (d) return d;
  }
  // mesma quantidade em tudo: quem ganhou antes o título mais importante vem primeiro
  for (const k of CRITERIOS) {
    const d = primeiroAno(a, k) - primeiroAno(b, k);
    if (d) return d;
  }
  return 0;
};
// `antesDe` (opcional): o time vai para logo antes do time indicado, do mesmo estado, fora da ordem de títulos.
// Única exceção hoje: o Remo fica à frente do Tuna Luso (o Tuna tem Série B e C; o Remo, Série C e Copa Verde).
const ordenado = estados.flatMap((uf) => {
  const lista = times.filter((t) => estado(t) === uf).sort(porTitulos);
  lista
    .filter((t) => t.antesDe)
    .forEach((t) => {
      lista.splice(lista.indexOf(t), 1);
      lista.splice(
        lista.findIndex((x) => x.slug === t.antesDe),
        0,
        t,
      );
    });
  return lista;
});
module.exports = ordenado;
